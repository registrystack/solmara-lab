    <div class="section-intro">
      <p class="eyebrow">No. 01 · How it works</p>
      <h2>The answer moves. The record does not.</h2>
      <p>
        A public service asks a small number of allowed questions. Each government office checks
        its own records and returns only the answers needed for that service.
      </p>
    </div>
    <ol class="model-steps">
      <li>
        <span class="model-number">1</span>
        <h3>The service asks</h3>
        <p>It explains why it is asking and requests only the answers needed for the application.</p>
      </li>
      <li>
        <span class="model-number">2</span>
        <h3>Each office checks</h3>
        <p>Every government office checks the records it already holds. No new master database is created.</p>
      </li>
      <li>
        <span class="model-number">3</span>
        <h3>Only answers return</h3>
        <p>The service receives the minimum yes-or-no answers, not addresses, scores, or registry rows.</p>
      </li>
      <li>
        <span class="model-number">4</span>
        <h3>The service decides</h3>
        <p>The service applies its own policy. Registry Stack never decides who receives a benefit.</p>
      </li>
    </ol>
  </div>
</section>
