      <p class="eyebrow">No. 01 · How it works</p>
      <h2>Keep authority with the source. Share only the evidence.</h2>
      <p>
        Solmara does not assemble a new national master database. Each authority keeps its records,
        evaluates a permitted question, and returns a bounded answer.
      </p>
    </div>
    <ol class="model-steps">
      <li>
        <span class="model-number">1</span>
        <h3>Ask a permitted question</h3>
        <p>A programme states its purpose and the minimum facts it needs.</p>
      </li>
      <li>
        <span class="model-number">2</span>
        <h3>Keep records at the source</h3>
        <p>Each authority evaluates only its own records and returns limited evidence.</p>
      </li>
      <li>
        <span class="model-number">3</span>
        <h3>Decide in the programme</h3>
        <p>The programme applies its policy. Registry Stack does not decide entitlement.</p>
      </li>
    </ol>
  </div>
